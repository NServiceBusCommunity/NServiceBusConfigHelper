/// <summary>
/// The download when features are added to an existing endpoint: not a solution, but the pieces to
/// merge into one. Each file is named for where it goes, and the guide walks through them in order.
/// </summary>
public static class AdditionGenerator
{
    public const string PackagesFragment = "Directory.Packages.props.fragment.xml";
    public const string ProjectFragment = "Endpoint.csproj.fragment.xml";
    public const string ProgramFragment = "Program.fragment.cs";
    public const string SettingsFragment = "appsettings.fragment.json";
    public const string ComposeFragment = "docker-compose.fragment.yml";
    public const string SamplesFolder = "Samples";

    public static IReadOnlyList<GeneratedFile> Build(Plan plan)
    {
        var files = new List<GeneratedFile>
        {
            new("readme.md", DocsGenerator.Build(plan)),
            new("ai-instructions.md", AiContentGenerator.Build(plan)),
            new(ProgramFragment, Program(plan))
        };

        if (plan.AddedPackages.Count > 0)
        {
            files.Add(new(PackagesFragment, Packages(plan)));
            files.Add(new(ProjectFragment, Project(plan)));
        }

        if (plan.Connections.Count > 0)
        {
            files.Add(new(SettingsFragment, ProjectFiles.AppSettings(plan)));
        }

        if (ProjectFiles.DockerCompose(plan) is { } compose)
        {
            files.Add(new(ComposeFragment, compose));
        }

        files.AddRange(FeatureFiles(plan));
        files.AddRange(Placeholders(plan).Select(_ => _ with {Path = $"{SamplesFolder}/{_.Path}"}));
        return files;
    }

    /// <summary>The features' own files, at the paths they take in the endpoint project.</summary>
    public static IReadOnlyList<GeneratedFile> FeatureFiles(Plan plan) =>
        [.. plan.Features.SelectMany(_ => SampleFiles.Feature(_, plan)).DistinctBy(_ => _.Path)];

    /// <summary>
    /// The sample messages and handler the features' files refer to, when any does. They stand in for
    /// the endpoint's own, so they are kept apart from what is meant to be copied as it is.
    /// </summary>
    public static IReadOnlyList<GeneratedFile> Placeholders(Plan plan)
    {
        if (!plan.Features.Any(_ => _.UsesSamples))
        {
            return [];
        }

        var taken = FeatureFiles(plan).Select(_ => _.Path).ToHashSet(StringComparer.Ordinal);
        return [.. SampleFiles.Placeholders(plan).Where(_ => !taken.Contains(_.Path))];
    }

    static string Packages(Plan plan)
    {
        var versions = plan.AddedPackages.Select(_ => $"""    <PackageVersion Include="{_}" Version="{plan.Version(_)}" />""");
        return
            $"""
             <!-- Merge into Directory.Packages.props. Without central package management, use these versions on the PackageReference items instead. -->
             <Project>
               <ItemGroup>
             {string.Join('\n', versions)}
               </ItemGroup>
             </Project>

             """;
    }

    static string Project(Plan plan)
    {
        var references = plan.AddedPackages.Select(_ => $"""    <PackageReference Include="{_}" />""");
        return
            $"""
             <!-- Merge into the endpoint's project file. -->
             <Project>
               <ItemGroup>
             {string.Join('\n', references)}
               </ItemGroup>
             </Project>

             """;
    }

    /// <summary>
    /// The statements to merge into wherever the endpoint is configured, grouped by where they go.
    /// It is a fragment, not a file that compiles: it refers to the endpoint's own
    /// <c>builder</c>, <c>endpointConfiguration</c> and <c>transport</c>.
    /// </summary>
    static string Program(Plan plan)
    {
        var blocks = new List<string>
        {
            $"""
             // Generated by the NServiceBus wizard: {plan.WizardUrl}
             // Statements to merge into the code that configures the endpoint. This is not a file to add:
             // it refers to the endpoint's own builder, endpointConfiguration and transport variables.
             """
        };

        var usings = ProgramGenerator.Usings(plan);
        if (usings.Count > 0)
        {
            blocks.Add(Section("Usings", usings.Select(_ => $"using {_};")));
        }

        blocks.AddRange(Sections("Before the host builder is created", ProgramGenerator.Startup(plan)));
        if (plan.Connections.Count > 0)
        {
            blocks.Add(
                Section(
                    "Connection strings. Use the endpoint's own way of reading configuration; these names are what the statements below refer to",
                    plan.Connections.Select(_ => $"var {_.Variable} = builder.Configuration.GetConnectionString(\"{_.Name}\")!;")));
        }

        blocks.AddRange(Sections("On the host builder", ProgramGenerator.HostBlocks(plan)));
        blocks.AddRange(Sections("On the endpoint configuration, before the endpoint is registered or started", ProgramGenerator.FeatureBlocks(plan)));
        return ProgramGenerator.Join(blocks);
    }

    static IEnumerable<string> Sections(string title, IEnumerable<string> blocks)
    {
        var list = blocks.ToList();
        if (list.Count == 0)
        {
            yield break;
        }

        yield return $"// ---- {title} ----";
        foreach (var block in list)
        {
            yield return block;
        }
    }

    static string Section(string title, IEnumerable<string> lines) =>
        $"// ---- {title} ----\n\n{string.Join('\n', lines)}";
}
