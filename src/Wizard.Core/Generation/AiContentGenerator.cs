/// <summary>
/// Instructions for an AI coding assistant: the AI tab and download, and the zip's CLAUDE.md and
/// .github/copilot-instructions.md. Project facts come first, then how to work with NServiceBus, then
/// what each selected feature means for a change.
/// </summary>
public static class AiContentGenerator
{
    public static string Build(Plan plan)
    {
        if (plan.IsAddition)
        {
            return BuildAddition(plan);
        }

        var builder = new MarkdownBuilder();
        builder.Heading(1, $"{plan.SolutionName}: instructions for AI coding assistants");
        builder.Paragraph($"Generated by the [NServiceBus wizard]({plan.WizardUrl}). This solution is an NServiceBus endpoint; the facts below describe how it is set up.");

        builder.Heading(2, "Project facts");
        builder.Bullets(Facts(plan));

        builder.Heading(2, "Working with NServiceBus");
        builder.Bullets(Guidance(plan));

        AppendFeatures(builder, plan);
        return builder.ToString();
    }

    static IEnumerable<string> Facts(Plan plan)
    {
        yield return $"Solution: `{plan.SolutionName}.slnx`. The endpoint is `src/{plan.EndpointProject}`, and its name on the transport is `{plan.EndpointName}`. Renaming it renames its queue.";
        yield return $"Target framework `{WizardDefaults.TargetFramework}`, SDK pinned by `global.json` ({WizardDefaults.SdkVersion}). NServiceBus {plan.Version("NServiceBus")}.";
        yield return "Packages use Central Package Management: add or change versions in `Directory.Packages.props`, and reference packages without a version.";
        yield return $"The whole endpoint configuration is in `src/{plan.EndpointProject}/Program.cs`. It is registered with `builder.Services.AddNServiceBusEndpoint(endpointConfiguration)` and starts and stops with the host.";
        yield return $"Transport: {plan.Transport.DisplayName}.";
        if (plan.UsesPersistence)
        {
            yield return $"Persistence: {plan.Persistence.DisplayName}.";
        }

        yield return $"Serializer: {plan.Serializer.DisplayName}. Message classes need a parameterless constructor and settable properties.";
        if (plan.Connections.Count > 0)
        {
            yield return $"Connection strings ({string.Join(", ", plan.Connections.Select(_ => $"`{_.Name}`"))}) are read from configuration in `Program.cs`; the development values are in `appsettings.json`.";
        }

        if (plan.Infrastructure.Count > 0)
        {
            yield return "`docker compose up -d` starts what the endpoint needs locally.";
        }

        if (plan.Installers)
        {
            yield return "`EnableInstallers()` is on: the endpoint creates its queues and tables when it starts.";
        }
        else
        {
            yield return "Installers are off: queues and tables have to exist before the endpoint starts. Do not turn them on to make a local run work without saying so.";
        }

        if (plan.Tests is { } tests)
        {
            yield return $"Tests are in `src/{plan.TestProject}`, with {tests.Framework.Name()} and NServiceBus.Testing. Run them from the solution directory with `{Plan.TestCommand}`.";
        }
    }

    static IEnumerable<string> Guidance(Plan plan)
    {
        if (plan.Conventions)
        {
            yield return $"A message is a plain class with no NServiceBus interface. A class in the namespace `{plan.CommandsNamespace}` is a command and one in `{plan.EventsNamespace}` is an event; putting a message anywhere else means NServiceBus does not recognise it.";
        }
        else
        {
            yield return $"A command implements `ICommand` and an event implements `IEvent`; both live in `{plan.MessagesNamespace}`.";
        }

        yield return "A command asks one endpoint to do something, is named in the imperative, and is sent. An event says something has happened, is named in the past tense, and is published. Never publish a command or send an event.";
        yield return "Changing or removing a property of a message breaks messages already in flight and endpoints not yet redeployed. Add properties; do not rename them.";
        if (plan.Receives)
        {
            yield return "A handler implements `IHandleMessages<T>` and is found by assembly scanning: adding the class is enough.";
            yield return "Inside a handler, send and publish through the `IMessageHandlerContext` it is given, never through `IMessageSession`: only then are the outgoing messages part of handling the incoming one.";
            yield return "Do not catch an exception in a handler to keep going. Let it throw: NServiceBus retries the message, then moves it to the `error` queue.";
            yield return IdempotencyFact(plan);
        }

        yield return "Outside a handler, send through `IMessageSession`, as `OrderSubmitter` does.";
        if (plan.Tests != null)
        {
            yield return "Test a handler by calling `Handle` with a `TestableMessageHandlerContext`, then asserting on its `SentMessages` and `PublishedMessages`. Test code that uses `IMessageSession` with a `TestableMessageSession`. No test needs a transport.";
        }
    }

    static string IdempotencyFact(Plan plan)
    {
        if (plan.Has(Features.Outbox))
        {
            return "The outbox is on, so a redelivered message is not processed twice as long as the handler's data goes through the persistence's own session. Anything else a handler touches, such as an http call, can still happen twice.";
        }

        return "A message can be delivered more than once, so a handler has to give the same result when it runs twice for the same message.";
    }

    /// <summary>What each feature is configured by and what it means for a change, then what the combination implies.</summary>
    static void AppendFeatures(MarkdownBuilder builder, Plan plan)
    {
        if (plan.Features.Count > 0)
        {
            builder.Heading(2, "Features of this endpoint");
            foreach (var feature in plan.Features)
            {
                builder.Heading(3, feature.DisplayName);
                var facts = new List<string>
                {
                    feature.Description,
                    $"Documentation: {feature.DocsUrl}"
                };
                if (feature.Code.Length > 0)
                {
                    facts.Add($"Configured by `{FirstStatement(feature.Code, plan)}`.");
                }

                var files = SampleFiles.Feature(feature, plan).Select(_ => $"`{_.Path}`").ToList();
                if (files.Count > 0)
                {
                    facts.Add($"Files: {string.Join(", ", files)}.");
                }

                foreach (var choice in feature.Choices)
                {
                    var value = plan.State.ChoiceValue(choice);
                    facts.Add($"{choice.Label}: {choice.Options.First(_ => _.Value == value).Label}.");
                }

                facts.AddRange(feature.Notes);
                builder.Bullets(facts);
            }
        }

        if (plan.Interactions.Count == 0)
        {
            return;
        }

        builder.Heading(2, "What the setup implies");
        builder.Bullets(plan.Interactions.Select(_ => $"**{string.Join(", ", _.Involved)}**: {_.Message}"));
    }

    /// <summary>The statement that names the feature's api, skipping comments and the lines that only prepare for it.</summary>
    static string FirstStatement(string code, Plan plan)
    {
        var lines = Template.Lines(Template.Render(code, plan))
            .Where(_ => !_.TrimStart().StartsWith("//", StringComparison.Ordinal))
            .ToList();
        var statement = lines.FirstOrDefault(_ => _.Contains("endpointConfiguration.", StringComparison.Ordinal)) ?? lines[0];
        return statement.Trim().TrimEnd('(');
    }

    /// <summary>
    /// For the add flow: an ordered task list for merging the download into an existing endpoint,
    /// each step naming the file it comes from, then the same feature notes.
    /// </summary>
    static string BuildAddition(Plan plan)
    {
        var builder = new MarkdownBuilder();
        builder.Heading(1, "Adding NServiceBus features: instructions for AI coding assistants");
        builder.Paragraph($"Generated by the [NServiceBus wizard]({plan.WizardUrl}). The files next to this one are changes to merge into an existing NServiceBus endpoint. Carry out the steps below in order. Find the endpoint's own configuration code first: the fragment's variable names are stand-ins for whatever that code uses.");

        builder.Heading(2, "Steps");
        builder.Numbered(
        [
            .. DocsGenerator.AdditionSteps(plan).SkipLast(1),
            "Build. Run the endpoint's tests if it has any. Do not start the endpoint against shared infrastructure without the user's agreement: with installers on, starting it creates queues and tables."
        ]);

        AppendFeatures(builder, plan);
        return builder.ToString();
    }
}
