/// <summary>
/// The guide: the Guide tab, the guide download, and the zip's readme.md. For a new endpoint it
/// explains what was generated and how to run it; for an addition it is the list of merges to make.
/// </summary>
public static class DocsGenerator
{
    public const string LicensingDocs = "https://docs.particular.net/nservicebus/licensing/";
    public const string InstallersDocs = "https://docs.particular.net/nservicebus/operations/installers";
    public const string TestingDocs = "https://docs.particular.net/nservicebus/testing/";
    public const string VerifyWizard = "https://verifytests.github.io/Wizard/add/NServiceBus";

    public static string Build(Plan plan)
    {
        if (plan.IsAddition)
        {
            return BuildAddition(plan);
        }

        var builder = new MarkdownBuilder();
        builder.Heading(1, plan.SolutionName);
        builder.Paragraph($"An NServiceBus endpoint generated by the [NServiceBus wizard]({plan.WizardUrl}). That link reopens the wizard with the same answers.");

        builder.Heading(2, "What is in the solution");
        builder.Bullets(Contents(plan));
        builder.Paragraph($"Package versions: {plan.VersionsNote}.");

        builder.Heading(2, "Before the first run");
        builder.Numbered(Prerequisites(plan));

        builder.Heading(2, "Run it");
        builder.Code($"dotnet run --project src/{plan.EndpointProject}", "sh");
        builder.Paragraph(RunNote(plan));

        builder.Heading(2, "How the endpoint is configured");
        builder.Paragraph($"All of it is in `src/{plan.EndpointProject}/Program.cs`, in the order below.");
        AppendComponent(builder, "Transport", plan.Transport, plan);
        if (plan.UsesPersistence)
        {
            AppendComponent(builder, "Persistence", plan.Persistence, plan);
        }

        AppendComponent(builder, "Serializer", plan.Serializer, plan);
        if (plan.Receives)
        {
            builder.Heading(3, "Error queue");
            builder.Paragraph("A message that still fails after its retries is moved to the `error` queue, with the exception in its headers, so the endpoint can carry on with the next one.");
            builder.Code(ProgramGenerator.ErrorQueue, "cs");
        }

        builder.Heading(3, "Installers");
        if (plan.Installers)
        {
            builder.Paragraph($"The endpoint creates its queues, topics and tables when it starts. That is convenient in development. In production, run [installers]({InstallersDocs}) as a deployment step instead, with rights the running endpoint does not need.");
            builder.Code(ProgramGenerator.InstallersCode, "cs");
        }
        else
        {
            builder.Paragraph($"Installers are off, so the endpoint creates nothing when it starts: its queues, topics and tables have to exist already. See [installers]({InstallersDocs}) for how to create them as a deployment step.");
        }

        foreach (var feature in plan.Features)
        {
            AppendFeature(builder, feature, plan);
        }

        builder.Heading(2, "The sample messages");
        builder.Bullets(Samples(plan));

        if (plan.Tests is { } tests)
        {
            builder.Heading(2, "Tests");
            builder.Paragraph($"`src/{plan.TestProject}` uses {tests.Framework.Name()} and [NServiceBus.Testing]({TestingDocs}), whose fakes record what a handler sends and publishes, so nothing needs a transport.");
            builder.Code(Plan.TestCommand, "sh");
        }

        AppendInteractions(builder, plan);

        builder.Heading(2, "Next steps");
        builder.Bullets(NextSteps(plan));
        return builder.ToString();
    }

    static IEnumerable<string> Contents(Plan plan)
    {
        yield return $"`src/{plan.EndpointProject}`: the endpoint `{plan.EndpointName}`, hosted as {HostingPhrase(plan)}.";
        if (plan.Tests is { } tests)
        {
            yield return $"`src/{plan.TestProject}`: {tests.Framework.Name()} tests.";
        }

        if (plan.Infrastructure.Count > 0)
        {
            yield return $"`docker-compose.yml`: {DisplayNames.Join([.. plan.Infrastructure.Select(_ => _.DisplayName)])}, for running locally.";
        }

        yield return "`CLAUDE.md` and `.github/copilot-instructions.md`: the same facts as this guide, written for an AI coding assistant.";
        yield return $"Transport: [{plan.Transport.DisplayName}]({plan.Transport.DocsUrl}).";
        if (plan.UsesPersistence)
        {
            yield return $"Persistence: [{plan.Persistence.DisplayName}]({plan.Persistence.DocsUrl}).";
        }

        yield return $"Serializer: [{plan.Serializer.DisplayName}]({plan.Serializer.DocsUrl}).";
        if (plan.Features.Count > 0)
        {
            yield return $"Features: {string.Join(", ", plan.Features.Select(_ => _.DisplayName))}.";
        }
    }

    static string HostingPhrase(Plan plan)
    {
        if (plan.Hosting == Hosting.AspNetCore)
        {
            return "an ASP.NET Core application";
        }

        return "a worker service";
    }

    static IEnumerable<string> Prerequisites(Plan plan)
    {
        yield return $"Install the .NET SDK {WizardDefaults.SdkVersion} or a later feature band; `global.json` pins it.";
        if (plan.Infrastructure.Count > 0)
        {
            yield return "Start the containers the endpoint needs: `docker compose up -d`. Their passwords are in `docker-compose.yml` and `appsettings.json` in the clear, which is fine for a container on a developer's machine and nowhere else.";
        }

        foreach (var note in plan.Infrastructure.SelectMany(_ => _.Notes))
        {
            yield return Template.Render(note, plan);
        }

        foreach (var connection in plan.Connections.Where(_ => _.Development.Length == 0))
        {
            yield return $"Set the `{connection.Name}` connection string, in `src/{plan.EndpointProject}/appsettings.json` or as the `ConnectionStrings__{connection.Name}` environment variable. {connection.Hint} The endpoint stops on startup, saying which one, until it is set.";
        }

        yield return $"NServiceBus is licensed by Particular Software. See [licensing]({LicensingDocs}) for the options and for where the licence file goes.";
    }

    static string RunNote(Plan plan)
    {
        if (plan.Hosting == Hosting.AspNetCore)
        {
            var post = "Then place an order, for example with `curl -X POST \"http://localhost:5000/orders?product=Widget\"`.";
            if (plan.Receives)
            {
                return $"{post} The log shows `PlaceOrder` being handled, and the `OrderPlaced` event it publishes being handled in turn.";
            }

            return $"{post} The command is sent to the `{SampleFiles.Destination}` endpoint, which this solution does not contain.";
        }

        if (plan.Receives)
        {
            return "On startup `SampleOrders` submits one order. The log shows `PlaceOrder` being handled, and the `OrderPlaced` event it publishes being handled in turn.";
        }

        return $"On startup `SampleOrders` submits one order, which is sent to the `{SampleFiles.Destination}` endpoint. This solution does not contain that endpoint.";
    }

    static void AppendComponent(MarkdownBuilder builder, string kind, ComponentDefinition component, Plan plan)
    {
        builder.Heading(3, $"{kind}: {component.DisplayName}");
        builder.Paragraph($"{component.Description} [Documentation]({component.DocsUrl}).");
        builder.Code(Template.Render(component.Code, plan), "cs");
        AppendDetails(builder, component, plan);
    }

    static void AppendFeature(MarkdownBuilder builder, FeatureDefinition feature, Plan plan)
    {
        builder.Heading(3, feature.DisplayName);
        var origin = "";
        if (feature.Community)
        {
            origin = " An NServiceBus Community extension.";
        }

        builder.Paragraph($"{feature.Description}{origin} [Documentation]({feature.DocsUrl}).");
        var code = new[] {feature.Startup, feature.Host, feature.Code}
            .Where(_ => _.Length > 0)
            .Select(_ => Template.Render(_, plan))
            .ToList();
        if (code.Count > 0)
        {
            builder.Code(string.Join("\n\n", code), "cs");
        }

        var files = SampleFiles.Feature(feature, plan).Select(_ => $"`{_.Path}`").ToList();
        if (files.Count > 0)
        {
            builder.Paragraph($"Files: {string.Join(", ", files)}.");
        }

        AppendDetails(builder, feature, plan);
    }

    /// <summary>The choices in force, the connection strings it reads, and its notes.</summary>
    static void AppendDetails(MarkdownBuilder builder, ComponentDefinition component, Plan plan)
    {
        var details = new List<string>();
        foreach (var choice in component.Choices)
        {
            var value = plan.State.ChoiceValue(choice);
            var option = choice.Options.First(_ => _.Value == value);
            details.Add($"{choice.Label}: {option.Label}. {option.Hint}");
        }

        foreach (var connection in component.Connections)
        {
            details.Add($"Reads the `{connection.Name}` connection string. {connection.Hint}");
        }

        details.AddRange(component.Notes);
        if (details.Count > 0)
        {
            builder.Bullets(details);
        }
    }

    static IEnumerable<string> Samples(Plan plan)
    {
        yield return $"`{plan.CommandsFolder}/PlaceOrder.cs` is a command: a request for one endpoint to do something.";
        if (plan.Receives)
        {
            yield return $"`{plan.EventsFolder}/OrderPlaced.cs` is an event: something that has happened, which any number of endpoints can subscribe to.";
            yield return "`Handlers/PlaceOrderHandler.cs` handles the command and publishes the event. `Handlers/OrderPlacedHandler.cs` handles the event, which is also what subscribes the endpoint to it.";
            yield return "`OrderSubmitter.cs` sends the command from outside a handler, through `IMessageSession`. Inside a handler, always send and publish through the context the handler is given, so the outgoing messages belong to the message being handled.";
        }
        else
        {
            yield return $"`OrderSubmitter.cs` sends the command through `IMessageSession`. `Program.cs` routes it to `{SampleFiles.Destination}`: replace that with the endpoint that handles it.";
        }

        if (plan.Hosting == Hosting.Worker)
        {
            yield return "`SampleOrders.cs` submits one order on startup. Delete it, and its registration in `Program.cs`, once the endpoint has real work.";
        }
        else
        {
            yield return "`POST /orders` in `Program.cs` submits an order.";
        }

        if (plan.Conventions)
        {
            yield return "The message classes implement no NServiceBus interface: the conventions in `Program.cs` recognise them by namespace.";
        }
    }

    static void AppendInteractions(MarkdownBuilder builder, Plan plan)
    {
        if (plan.Interactions.Count == 0)
        {
            return;
        }

        builder.Heading(2, "Worth knowing");
        builder.Bullets(plan.Interactions.Select(_ => $"**{string.Join(", ", _.Involved)}**: {_.Message}"));
    }

    static IEnumerable<string> NextSteps(Plan plan)
    {
        yield return $"Install [ServiceControl and ServicePulse]({InteractionRules.ServiceControlDocs}) to see failed messages and retry them.";
        if (plan.Tests != null)
        {
            yield return $"Snapshot test what a handler sends with Verify.NServiceBus; the [Verify wizard]({VerifyWizard}) sets it up.";
        }

        yield return $"Add another feature later with the [add flow]({WizardLinks.Add}), which generates only what has to be merged.";
    }

    static string BuildAddition(Plan plan)
    {
        var builder = new MarkdownBuilder();
        builder.Heading(1, "Adding features to an NServiceBus endpoint");
        builder.Paragraph($"Generated by the [NServiceBus wizard]({plan.WizardUrl}). The files next to this guide are changes to merge into an existing endpoint, not a solution. Adding: {string.Join(", ", plan.Features.Select(_ => _.DisplayName))}.");
        builder.Paragraph($"Package versions: {plan.VersionsNote}.");

        builder.Heading(2, "Steps");
        builder.Numbered(AdditionSteps(plan));

        builder.Heading(2, "What each feature adds");
        foreach (var feature in plan.Features)
        {
            AppendFeature(builder, feature, plan);
        }

        AppendInteractions(builder, plan);
        return builder.ToString();
    }

    public static IEnumerable<string> AdditionSteps(Plan plan)
    {
        if (plan.AddedPackages.Count > 0)
        {
            yield return $"Merge the `PackageVersion` items from `{AdditionGenerator.PackagesFragment}` into `Directory.Packages.props`. Without central package management, put each version on the matching `PackageReference` in the next step instead.";
            yield return $"Merge the `PackageReference` items from `{AdditionGenerator.ProjectFragment}` into the endpoint's project file.";
        }

        yield return $"Merge `{AdditionGenerator.ProgramFragment}` into the code that configures the endpoint. It is grouped by where each statement goes, and refers to the endpoint's own `builder`, `endpointConfiguration` and `transport` variables.";

        if (plan.Connections.Count > 0)
        {
            yield return $"Add the connection strings in `{AdditionGenerator.SettingsFragment}` to the endpoint's settings, or point the statements at connection strings it already has.";
        }

        if (plan.Infrastructure.Count > 0)
        {
            yield return $"For a local run, `{AdditionGenerator.ComposeFragment}` has a container for {DisplayNames.Join([.. plan.Infrastructure.Select(_ => _.DisplayName)])}. Its password is in the clear, which is fine for a container on a developer's machine and nowhere else.";
        }

        foreach (var note in plan.Infrastructure.SelectMany(_ => _.Notes))
        {
            yield return Template.Render(note, plan);
        }

        var files = AdditionGenerator.FeatureFiles(plan);
        if (files.Count > 0)
        {
            yield return $"Copy {string.Join(", ", files.Select(_ => $"`{_.Path}`"))} into the endpoint project, and change the namespace `{plan.Namespace}` to the project's own.";
        }

        if (AdditionGenerator.Placeholders(plan).Count > 0)
        {
            yield return $"Those files refer to sample messages and a sample handler, which are in `{AdditionGenerator.SamplesFolder}/`. Point the copied code at the endpoint's own messages instead, or copy the samples too.";
        }

        yield return "Build and run the endpoint.";
    }
}
