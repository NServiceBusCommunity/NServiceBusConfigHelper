/// <summary>
/// The endpoint's <c>Program.cs</c>, assembled from the code each component holds in the registry.
/// The same sections make up the fragment the add flow hands over for merging, so the two cannot drift.
/// </summary>
public static class ProgramGenerator
{
    public const string ErrorQueue =
        """
        // Where a message goes once every retry has failed. ServiceControl reads this queue.
        endpointConfiguration.SendFailedMessagesTo("error");
        """;

    public const string InstallersCode =
        """
        // Creates the queues, topics and tables the endpoint needs when it starts. Convenient in development.
        // In production, run installers as a deployment step, with rights the running endpoint does not need.
        endpointConfiguration.EnableInstallers();
        """;

    const string connectionFunction =
        """
        string ConnectionString(string name)
        {
            var value = builder.Configuration.GetConnectionString(name);
            if (string.IsNullOrWhiteSpace(value))
            {
                throw new InvalidOperationException(
                    $"Connection string '{name}' is not set. Add it to appsettings.json, or set the ConnectionStrings__{name} environment variable.");
            }

            return value;
        }
        """;

    public static string Build(Plan plan)
    {
        var blocks = new List<string>
        {
            Header(plan)
        };
        blocks.AddRange(Startup(plan));

        if (plan.Hosting == Hosting.AspNetCore)
        {
            blocks.Add("var builder = WebApplication.CreateBuilder(args);");
        }
        else
        {
            blocks.Add("var builder = Host.CreateApplicationBuilder(args);");
        }

        if (plan.Connections.Count > 0)
        {
            blocks.Add(ConnectionLines(plan));
        }

        blocks.AddRange(HostBlocks(plan));
        blocks.Add($"var endpointConfiguration = new EndpointConfiguration(\"{plan.EndpointName}\");");
        blocks.Add(TransportBlock(plan));
        if (plan.UsesPersistence)
        {
            blocks.Add(ComponentBlock("Persistence", plan.Persistence, plan));
        }

        blocks.Add(ComponentBlock("Serializer", plan.Serializer, plan));
        if (plan.Receives)
        {
            blocks.Add(ErrorQueue);
        }

        blocks.AddRange(FeatureBlocks(plan));
        if (plan.Installers)
        {
            blocks.Add(InstallersCode);
        }

        blocks.Add(Registration(plan));
        blocks.Add(Run(plan));
        if (plan.Connections.Count > 0)
        {
            blocks.Add(connectionFunction);
        }

        return Join(blocks);
    }

    static string Header(Plan plan)
    {
        var lines = new List<string>
        {
            $"// Generated by the NServiceBus wizard: {plan.WizardUrl}"
        };
        lines.AddRange(Usings(plan).Select(_ => $"using {_};"));
        return string.Join('\n', lines);
    }

    /// <summary>
    /// What the components' code needs. A new endpoint's Program.cs also names the sample types, which
    /// are in the project's namespace, and the commands namespace when a route names a command.
    /// </summary>
    public static IReadOnlyList<string> Usings(Plan plan)
    {
        var usings = plan.Components.SelectMany(_ => _.Usings).ToList();
        if (!plan.IsAddition)
        {
            usings.Add(plan.Namespace);
        }

        if (plan is {SendOnly: true, IsAddition: false})
        {
            usings.Add(plan.CommandsNamespace);
        }

        return [.. usings.Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal)];
    }

    /// <summary>Statements that have to run before the host builder is created.</summary>
    public static IEnumerable<string> Startup(Plan plan) =>
        plan.Features
            .Where(_ => _.Startup.Length > 0)
            .Select(_ => $"{FeatureComment(_)}\n{Template.Render(_.Startup, plan)}");

    /// <summary>One local per connection string, read from configuration.</summary>
    public static string ConnectionLines(Plan plan) =>
        string.Join('\n', plan.Connections.Select(_ => $"var {_.Variable} = ConnectionString(\"{_.Name}\");"));

    /// <summary>Statements on the host builder: services and logging.</summary>
    public static IEnumerable<string> HostBlocks(Plan plan) =>
        plan.Features
            .Where(_ => _.Host.Length > 0)
            .Select(_ => $"{FeatureComment(_)}\n{Template.Render(_.Host, plan)}");

    /// <summary>Statements on the endpoint configuration, one block per feature, in registry order.</summary>
    public static IEnumerable<string> FeatureBlocks(Plan plan) =>
        plan.Features
            .Where(_ => _.Code.Length > 0)
            .Select(_ => $"{FeatureComment(_)}\n{Template.Render(_.Code, plan)}");

    static string FeatureComment(FeatureDefinition feature) =>
        $"// {feature.DisplayName}: {feature.DocsUrl}";

    static string ComponentBlock(string kind, ComponentDefinition component, Plan plan) =>
        $"// {kind}: {component.DisplayName}. {component.DocsUrl}\n{Template.Render(component.Code, plan)}";

    static string TransportBlock(Plan plan)
    {
        var block = ComponentBlock("Transport", plan.Transport, plan);
        if (plan.Receives)
        {
            return $"{block}\nendpointConfiguration.UseTransport(transport);";
        }

        return
            $"""
             {block}
             var routing = endpointConfiguration.UseTransport(transport);
             // A send-only endpoint cannot send to itself, so every command needs a route. "{SampleFiles.Destination}" stands
             // for the endpoint that handles PlaceOrder.
             routing.RouteToEndpoint(typeof(PlaceOrder), "{SampleFiles.Destination}");
             """;
    }

    static string Registration(Plan plan)
    {
        var lines = new List<string>
        {
            "builder.Services.AddNServiceBusEndpoint(endpointConfiguration);",
            "builder.Services.AddSingleton<OrderSubmitter>();"
        };
        if (plan.Hosting == Hosting.Worker)
        {
            lines.Add("builder.Services.AddHostedService<SampleOrders>();");
        }

        return string.Join('\n', lines);
    }

    static string Run(Plan plan)
    {
        if (plan.Hosting == Hosting.Worker)
        {
            return "await builder.Build().RunAsync();";
        }

        return
            """
            var app = builder.Build();

            // POST /orders?product=Widget
            app.MapPost(
                "/orders",
                async (string product, OrderSubmitter submitter, CancellationToken cancellationToken) =>
                {
                    var orderId = await submitter.Submit(product, cancellationToken);
                    return Results.Accepted(value: new {orderId});
                });

            await app.RunAsync();
            """;
    }

    /// <summary>Blocks separated by one blank line, lf line endings, one trailing newline.</summary>
    public static string Join(IEnumerable<string> blocks) =>
        string.Join("\n\n", blocks.Select(_ => _.Replace("\r\n", "\n").Trim('\n'))) + "\n";
}
